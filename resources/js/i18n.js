const savedLocale = typeof window !== 'undefined' ? localStorage.getItem('bsc_locale') : null;
const initialLocale = savedLocale || 'am';

export const i18n = createI18n({
    legacy: false,
    locale: initialLocale,
    fallbackLocale: 'en',
    messages,
});

export function setLocale(lang) {
    i18n.global.locale.value = lang;
    if (typeof window !== 'undefined') {
        localStorage.setItem('bsc_locale', lang);
        document.documentElement.lang = lang;
    }
}
